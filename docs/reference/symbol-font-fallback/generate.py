#!/usr/bin/env python3
"""Generate legacy font lookup tables from pinned Unicode data; --check rejects drift."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / 'data'
TARGET = ROOT / 'SymbolMappingData.swift'

def generate():
    tables = {name: {} for name in ('symbol', 'webdings', 'wingdings', 'wingdings2', 'wingdings3')}
    for line in (DATA / 'adobe-symbol.txt').read_text().splitlines():
        if not line or line.startswith('#'): continue
        scalar, code, *_ = line.split()
        value = int(scalar, 16)
        # Corporate-use glyph pieces have no portable Unicode glyph. Keep them unmapped.
        if not 0xE000 <= value <= 0xF8FF:
            tables['symbol'].setdefault(int(code, 16), value)
    names = ['webdings', 'wingdings', 'wingdings2', 'wingdings3']
    for line in (DATA / 'wingdings-mapping.txt').read_text().splitlines():
        if line.startswith('#') or not line: continue
        index, scalar = line.split(';')
        index = int(index)
        tables[names[index // 1000]][index % 1000] = int(scalar, 16)
    for name in names: tables[name][32] = 32
    assert all(len(table) > 150 for table in tables.values()), 'empty/incomplete mapping data'
    out = ['// Generated by generate.py; do not edit.',
           '// Unicode data attribution and sources: README.md and data/UNICODE-LICENSE.txt.',
           'enum SymbolMappingData {']
    for name, table in tables.items():
        out.append(f'    static let {name}: [UInt8: UInt32] = [')
        items = [f'0x{k:02X}: 0x{v:X}' for k,v in sorted(table.items())]
        for i in range(0,len(items),6): out.append('        ' + ', '.join(items[i:i+6]) + ',')
        out.append('    ]')
    scalars = [line for line in (DATA/'text-presentation.txt').read_text().splitlines() if line and not line.startswith('#')]
    out.append('    static let textPresentation: Set<UInt32> = [')
    for i in range(0,len(scalars),12): out.append('        ' + ', '.join('0x'+s for s in scalars[i:i+12]) + ',')
    out.extend(['    ]', '}', ''])
    return '\n'.join(out)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content: raise SystemExit('Generated symbol tables are stale')
        print('Pinned symbol mappings match generated Swift tables')
    else: TARGET.write_text(content)
